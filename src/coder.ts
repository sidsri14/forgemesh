export interface RateLimiterOptions {
  windowMs: number;
  maxRequests: number;
}

export class DistributedRateLimiter {
  private requests: Map<string, number[]> = new Map();
  private options: RateLimiterOptions;

  constructor(options: RateLimiterOptions) {
    if (options.maxRequests <= 0 || options.windowMs <= 0) {
      throw new Error("Invalid rate limiter parameters");
    }
    this.options = options;
  }

  public isAllowed(clientId: string, now: number = Date.now()): boolean {
    const windowStart = now - this.options.windowMs;
    const timestamps = (this.requests.get(clientId) || []).filter(t => t > windowStart);
    
    if (timestamps.length >= this.options.maxRequests) {
      return false;
    }

    timestamps.push(now);
    this.requests.set(clientId, timestamps);
    return true;
  }

  public getRemaining(clientId: string, now: number = Date.now()): number {
    const windowStart = now - this.options.windowMs;
    const timestamps = (this.requests.get(clientId) || []).filter(t => t > windowStart);
    return Math.max(0, this.options.maxRequests - timestamps.length);
  }

  public reset(clientId: string): void {
    this.requests.delete(clientId);
  }
}
